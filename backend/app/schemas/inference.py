"""Pydantic schemas for Vultr Serverless Inference test planning."""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, model_validator


class DiscoveredToolInput(BaseModel):
    """MCP tool definition passed for test plan generation."""
    tool_name: str = Field(description="Name of the MCP tool")
    description: str = Field(default="", description="Tool documentation or summary")
    input_schema: Dict[str, Any] = Field(
        default_factory=dict, description="JSON Schema for tool arguments"
    )


class TestStep(BaseModel):
    """An individual tool call step within a verification scenario."""
    __test__ = False
    step_index: int = Field(ge=1, le=2, description="Sequence index: 1 or 2")
    tool_name: str = Field(description="Target tool to call")
    arguments: Dict[str, Any] = Field(
        default_factory=dict, description="Simple arguments for the tool"
    )
    expected_result: str = Field(
        default="", description="Concise expected outcome (under 15 words)"
    )
    expected_behavior: Optional[str] = Field(
        default=None, description="Legacy alias for expected_result"
    )

    @model_validator(mode="before")
    @classmethod
    def sync_expected_fields(cls, data: Any) -> Any:
        if isinstance(data, dict):
            if "expected_behavior" in data and not data.get("expected_result"):
                data["expected_result"] = data["expected_behavior"]
            elif "expected_result" in data and not data.get("expected_behavior"):
                data["expected_behavior"] = data["expected_result"]
        return data


class TestScenario(BaseModel):
    """A scenario containing one or two ordered tool-call steps."""
    __test__ = False
    scenario_id: str = Field(description="Short slug (e.g. sc-1)")
    title: str = Field(description="Short scenario name (under 6 words)")
    objective: str = Field(description="Short action description (under 15 words)")
    safety_classification: str = Field(
        default="benign_baseline",
        description="Classification: benign_baseline, canary_probe, boundary_check",
    )
    steps: List[TestStep] = Field(
        min_length=1,
        max_length=2,
        description="At most 2 test steps per scenario",
    )


class TestPlan(BaseModel):
    """Structured test plan generated by the LLM."""
    __test__ = False
    plan_id: str = Field(description="Short plan identifier (e.g. plan-1)")
    target_server_summary: str = Field(
        description="One-sentence server summary (under 15 words)"
    )
    coverage_notes: Optional[str] = Field(
        default=None,
        description="Optional brief notes",
    )
    scenarios: List[TestScenario] = Field(
        min_length=1,
        max_length=3,
        description="At most 3 generated test scenarios",
    )


class GenerationRequest(BaseModel):
    """Client request to generate an AI test plan."""
    repository_url: str = Field(description="Target GitHub repository URL")
    tools: List[DiscoveredToolInput] = Field(
        min_length=1, description="Discovered MCP tools to formulate tests for"
    )
    model_id: Optional[str] = Field(
        default=None,
        description="Optional model ID override (e.g. qwen3.8-flash-next)",
    )
    max_tokens: Optional[int] = Field(
        default=None,
        description="Optional output token limit override (default: 2500)",
    )


class GenerationResponse(BaseModel):
    """API response containing the structured test plan."""
    status: str = Field(default="success", description="Generation outcome")
    model: str = Field(description="Model used for generation")
    plan: Optional[TestPlan] = Field(default=None, description="Generated structured test plan")
    usage: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Token usage (prompt_tokens, completion_tokens, total_tokens, details)",
    )
    duration_ms: float = Field(description="Inference call duration in milliseconds")


class InferenceConfigStatus(BaseModel):
    """Configuration status of Vultr Serverless Inference (without making paid calls)."""
    api_key_configured: bool = Field(description="Whether a non-empty API key is configured")
    configured_model: Optional[str] = Field(
        description="Configured model identifier"
    )
    base_url: str = Field(description="Vultr inference base URL")
    benchmark_models: List[str] = Field(
        default=["qwen3.8-flash-next"],
        description="Target benchmark models from live catalogue",
    )
